  iniciar() {
    if (typeof document === 'undefined' || this.observador) return;
    this.observador = new MutationObserver(cambios => {
      for (const cambio of cambios) {
        if (cambio.type === 'characterData' && cambio.target instanceof Text) this.traducirNodo(cambio.target);
        if (cambio.type === 'attributes' && cambio.target instanceof Element) this.traducirAtributos(cambio.target);
        for (const nodo of Array.from(cambio.addedNodes)) this.recorrer(nodo);
      }
    });
    this.observador.observe(document.body, {
      subtree: true, childList: true, characterData: true, attributes: true,
      attributeFilter: ['placeholder','title','aria-label','aria-description','alt']
    });
    this.aplicarIdioma();
  }

  cambiar(idioma: string) {
    if (!['es','en','qu','pt'].includes(idioma)) return;
    this.idioma.set(idioma as Idioma);
    localStorage.setItem('agro-idioma', idioma);
    this.aplicarIdioma();
  }

  t(texto: string): string { return this.traducir(texto, this.idioma()); }

  private aplicarIdioma() {
    document.documentElement.lang = this.idioma();
    this.recorrer(document.body);
  }

  private recorrer(nodo: Node) {
    if (nodo.nodeType === Node.TEXT_NODE) { this.traducirNodo(nodo as Text); return; }
    if (!(nodo instanceof Element) || this.excluido(nodo)) return;
    this.traducirAtributos(nodo);
    if (nodo.matches('input,textarea')) return;
    for (const hijo of Array.from(nodo.childNodes)) this.recorrer(hijo);
  }

  private excluido(elemento: Element) {
    return elemento.matches('script,style,svg,code,pre,[contenteditable="true"],[data-no-translate]') ||
      Boolean(elemento.closest('[data-no-translate]'));
  }

  private traducirNodo(nodo: Text) {
    const padre = nodo.parentElement;
    if (!padre || this.excluido(padre)) return;
    const actual = nodo.nodeValue ?? '';
    const previo = this.originales.get(nodo);
    const original = previo && actual === previo.traducido ? previo.original : actual;
    const traducido = this.traducir(original, this.idioma());
    this.originales.set(nodo, { original, traducido });
    if (actual !== traducido) nodo.nodeValue = traducido;
  }

  private traducirAtributos(elemento: Element) {
    const nombres = ['placeholder','title','aria-label','aria-description','alt'];
    let registros = this.atributos.get(elemento);
    if (!registros) { registros = new Map(); this.atributos.set(elemento, registros); }
    for (const nombre of nombres) {
      const actual = elemento.getAttribute(nombre);
      if (actual == null) continue;
      const previo = registros.get(nombre);
      const original = previo && actual === previo.traducido ? previo.original : actual;
      const traducido = this.traducir(original, this.idioma());
      registros.set(nombre, { original, traducido });
      if (actual !== traducido) elemento.setAttribute(nombre, traducido);
    }
  }

  private traducir(texto: string, idioma: Idioma): string {
    if (idioma === 'es' || !texto.trim()) return texto;
    const diccionario = { ...this.frases[idioma], ...this.frasesExtra[idioma] };
    const inicio = texto.match(/^\s*/)?.[0] ?? '';
    const final = texto.match(/\s*$/)?.[0] ?? '';
    const limpio = texto.trim();
    if (diccionario[limpio]) return inicio + diccionario[limpio] + final;

    let resultado = limpio;
    const frases = Object.entries(diccionario).sort((a,b) => b[0].length - a[0].length);
    for (const [origen,destino] of frases) {
      const escaped = origen.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      resultado = resultado.replace(new RegExp(escaped, 'gi'), destino);
    }
    const palabras = this.palabras[idioma];
    resultado = resultado.replace(/\p{L}[\p{L}\p{M}]*/gu, palabra => {
      const clave = palabra.toLocaleLowerCase('es');
      const destino = palabras[clave] ?? this.palabrasExtra[idioma][clave];
      if (!destino) return palabra;
      return palabra[0] === palabra[0].toLocaleUpperCase('es')
        ? destino.charAt(0).toLocaleUpperCase(idioma === 'qu' ? 'es' : idioma) + destino.slice(1)
        : destino;
    });
    return inicio + resultado + final;
  }
