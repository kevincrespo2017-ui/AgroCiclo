ALTER TABLE usuarios
    ADD COLUMN estado_aprobacion varchar(12) NOT NULL DEFAULT 'APROBADO',
    ADD COLUMN verificacion_manual boolean NOT NULL DEFAULT false,
    ADD COLUMN motivo_rechazo varchar(300),
    ADD COLUMN creado_en timestamptz NOT NULL DEFAULT now();

ALTER TABLE usuarios ADD CONSTRAINT usuarios_estado_aprobacion_check
    CHECK (estado_aprobacion IN ('PENDIENTE', 'APROBADO', 'RECHAZADO'));

ALTER TABLE terrenos
    ADD COLUMN imagen_url varchar(500),
    ADD COLUMN latitud numeric(10,7),
    ADD COLUMN longitud numeric(10,7);
ALTER TABLE terrenos ADD CONSTRAINT terrenos_latitud_check CHECK (latitud IS NULL OR latitud BETWEEN -90 AND 90);
ALTER TABLE terrenos ADD CONSTRAINT terrenos_longitud_check CHECK (longitud IS NULL OR longitud BETWEEN -180 AND 180);

CREATE TABLE notificaciones (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id integer REFERENCES usuarios(id) ON DELETE CASCADE,
    rol_destino varchar(12) CHECK (rol_destino IN ('ADMIN', 'OPERATIVO')),
    titulo varchar(120) NOT NULL,
    mensaje varchar(500) NOT NULL,
    tipo varchar(24) NOT NULL DEFAULT 'SISTEMA',
    ruta varchar(200),
    creada_en timestamptz NOT NULL DEFAULT now(),
    leida_en timestamptz,
    CONSTRAINT notificaciones_destino_check CHECK (
      (usuario_id IS NOT NULL AND rol_destino IS NULL) OR
      (usuario_id IS NULL AND rol_destino IS NOT NULL)
    )
);
CREATE INDEX notificaciones_usuario_fecha_idx ON notificaciones(usuario_id, creada_en DESC);
CREATE INDEX notificaciones_rol_fecha_idx ON notificaciones(rol_destino, creada_en DESC);
