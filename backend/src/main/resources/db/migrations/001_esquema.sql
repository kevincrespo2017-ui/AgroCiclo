CREATE TABLE usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    email varchar(254) NOT NULL UNIQUE CHECK (email = lower(email)),
    password_hash text NOT NULL,
    rol varchar(12) NOT NULL CHECK (rol IN ('ADMIN', 'OPERATIVO'))
);

CREATE TABLE sesiones (
    token_hash char(64) PRIMARY KEY,
    usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    expira_en timestamptz NOT NULL
);
CREATE INDEX sesiones_usuario_idx ON sesiones (usuario_id, expira_en);

CREATE TABLE terrenos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    ubicacion varchar(120) NOT NULL,
    area_ha numeric(10,3) NOT NULL CHECK (area_ha > 0)
);
CREATE UNIQUE INDEX terrenos_nombre_unico ON terrenos (lower(nombre));

CREATE TABLE cultivos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    dias_estimados integer NOT NULL CHECK (dias_estimados BETWEEN 1 AND 730)
);
CREATE UNIQUE INDEX cultivos_nombre_unico ON cultivos (lower(nombre));

CREATE TABLE ciclos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo varchar(30) NOT NULL UNIQUE CHECK (codigo = upper(codigo)),
    terreno_id integer NOT NULL REFERENCES terrenos(id),
    cultivo_id integer NOT NULL REFERENCES cultivos(id),
    area_ha numeric(10,3) NOT NULL CHECK (area_ha > 0),
    estado varchar(12) NOT NULL DEFAULT 'PLANIFICADO'
        CHECK (estado IN ('PLANIFICADO', 'SEMBRADO', 'CERRADO')),
    fecha_inicio date NOT NULL,
    fecha_siembra date,
    fecha_estimada date,
    fecha_cierre date,
    notas varchar(500) NOT NULL DEFAULT '',
    CHECK (fecha_siembra >= fecha_inicio),
    CHECK (fecha_estimada >= fecha_siembra),
    CHECK (fecha_cierre >= fecha_siembra),
    CHECK (
        (estado = 'PLANIFICADO' AND fecha_siembra IS NULL AND fecha_estimada IS NULL AND fecha_cierre IS NULL)
        OR (estado = 'SEMBRADO' AND fecha_siembra IS NOT NULL AND fecha_estimada IS NOT NULL AND fecha_cierre IS NULL)
        OR (estado = 'CERRADO' AND fecha_siembra IS NOT NULL AND fecha_estimada IS NOT NULL AND fecha_cierre IS NOT NULL)
    )
);
CREATE INDEX ciclos_busqueda_idx ON ciclos (estado, cultivo_id, fecha_inicio DESC, id DESC);
CREATE INDEX ciclos_terreno_idx ON ciclos (terreno_id);
CREATE INDEX ciclos_cultivo_idx ON ciclos (cultivo_id);

CREATE TABLE actividades (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciclo_id integer NOT NULL REFERENCES ciclos(id),
    nombre varchar(100) NOT NULL,
    programada_para date NOT NULL,
    obligatoria boolean NOT NULL DEFAULT false,
    completada_en date,
    costo numeric(12,2) NOT NULL DEFAULT 0 CHECK (costo >= 0),
    nota varchar(500) NOT NULL DEFAULT '',
    CHECK (completada_en IS NOT NULL OR costo = 0)
);
CREATE INDEX actividades_ciclo_idx ON actividades (ciclo_id, programada_para, id);
CREATE INDEX actividades_alerta_idx ON actividades (programada_para)
    WHERE obligatoria AND completada_en IS NULL;

CREATE TABLE insumos (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    categoria varchar(16) NOT NULL CHECK (categoria IN ('FERTILIZANTE', 'SEMILLA', 'FITOSANITARIO', 'OTRO')),
    unidad varchar(2) NOT NULL CHECK (unidad IN ('KG', 'L', 'UN')),
    stock numeric(12,3) NOT NULL DEFAULT 0 CHECK (stock >= 0),
    stock_minimo numeric(12,3) NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    CHECK (unidad <> 'UN' OR (stock = trunc(stock) AND stock_minimo = trunc(stock_minimo)))
);
CREATE UNIQUE INDEX insumos_nombre_unico ON insumos (lower(nombre));

CREATE TABLE movimientos_insumo (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    insumo_id integer NOT NULL REFERENCES insumos(id),
    ciclo_id integer REFERENCES ciclos(id),
    tipo varchar(7) NOT NULL CHECK (tipo IN ('ENTRADA', 'CONSUMO')),
    folio varchar(30) NOT NULL CHECK (folio = upper(folio)),
    fecha date NOT NULL,
    cantidad numeric(12,3) NOT NULL CHECK (cantidad > 0),
    costo_unitario numeric(12,2) NOT NULL CHECK (costo_unitario >= 0),
    CHECK ((tipo = 'ENTRADA' AND ciclo_id IS NULL) OR (tipo = 'CONSUMO' AND ciclo_id IS NOT NULL)),
    CONSTRAINT movimientos_folio_unico UNIQUE (insumo_id, tipo, folio)
);
CREATE INDEX movimientos_ciclo_idx ON movimientos_insumo (ciclo_id, fecha DESC);

CREATE TABLE cosechas (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ciclo_id integer NOT NULL REFERENCES ciclos(id),
    folio varchar(30) NOT NULL CHECK (folio = upper(folio)),
    fecha date NOT NULL,
    kilogramos numeric(12,3) NOT NULL CHECK (kilogramos > 0),
    nota varchar(500) NOT NULL DEFAULT '',
    CONSTRAINT cosechas_folio_unico UNIQUE (ciclo_id, folio)
);
CREATE INDEX cosechas_ciclo_idx ON cosechas (ciclo_id, fecha DESC);

CREATE TABLE auditoria (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id integer NOT NULL REFERENCES usuarios(id),
    fecha_hora timestamptz NOT NULL DEFAULT now(),
    accion varchar(40) NOT NULL,
    entidad varchar(30) NOT NULL,
    registro_id integer NOT NULL,
    detalle jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX auditoria_fecha_idx ON auditoria (fecha_hora DESC, id DESC);

CREATE TABLE cargas_demo (
    nombre text PRIMARY KEY
);
